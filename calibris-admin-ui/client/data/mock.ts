export function countByStatus(list: Device[]) {
  return list.reduce(
    (acc, d) => {
      acc.total += 1;
      if (d.status === "OK" || d.status === "Online") acc.online += 1;
      if (d.status === "Offline") acc.offline += 1;
      if (d.status === "Tampered" || d.status === "safe_mode") acc.tampered += 1;
      if (d.status === "Drifted") acc.drifted += 1;
      return acc;
    },
    { total: 0, online: 0, offline: 0, tampered: 0, drifted: 0 },
  );
}
